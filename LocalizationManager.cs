    public static LanguageInfo[] SupportedLanguages => Languages;

    public static void SetLanguage(string code)
    {
        CurrentLanguage = Strings.ContainsKey(code) ? code : "ru";
    }

    public static void InitSystemLanguage()
    {
        CurrentLanguage = DetectSystemLanguage();
    }

    public static string DetectSystemLanguage()
    {
        try
        {
            var culture = CultureInfo.CurrentUICulture;
            string code = culture.TwoLetterISOLanguageName.ToLowerInvariant();
            if (code == "zh") return "zh";
            if (Strings.ContainsKey(code)) return code;
        }
        catch { }
        return "ru";
    }

    public static string GetString(string key)
    {
        if (Strings.TryGetValue(CurrentLanguage, out var dict) && dict.TryGetValue(key, out var val))
            return val;
        if (Strings.TryGetValue("en", out var enDict) && enDict.TryGetValue(key, out var enVal))
            return enVal;
        if (Strings.TryGetValue("ru", out var ruDict) && ruDict.TryGetValue(key, out var ruVal))
            return ruVal;
        return key;
    }

